"""
Ragas Evaluation Engine.

Provides functionality to evaluate the RAG pipeline using Ragas metrics,
fully configured to use Google Gemini 2.5 Flash as the evaluation judge.
"""

from typing import Dict, List, Any, Optional
import pandas as pd
from datasets import Dataset

from ragas import evaluate
from ragas.metrics import (
    faithfulness,
    answer_relevancy,
    context_precision,
    context_recall,
)
from ragas.llms import LangchainLLMWrapper
from ragas.embeddings import LangchainEmbeddingsWrapper
from langchain_google_genai import ChatGoogleGenerativeAI, GoogleGenerativeAIEmbeddings

from langchain_openai import ChatOpenAI
from src.config.config import settings

class RagasEvaluator:
    """
    Evaluator class for assessing RAG pipeline performance.
    
    Why RAG Evaluation is Crucial:
    Traditional software testing (asserting exact string matches) fails on LLM outputs
    because LLM responses are non-deterministic and can be worded differently each time.
    Ragas evaluates semantic quality without requiring string matches, scoring metrics from 0 to 1.
    
    Ragas Metrics Explained:
    1. Faithfulness (Groundedness):
       - Measures if the generated answer is derived *only* from the retrieved context.
       - Identifies hallucinations. (Formula: number of claims in answer supported by context / total claims in answer).
    2. Context Recall:
       - Measures if the retriever successfully retrieved all necessary info to answer the question.
       - Evaluated against the ground truth. (Formula: ground truth sentences supported by context / total ground truth sentences).
    3. Context Precision:
       - Measures if the relevant chunks were ranked higher than irrelevant ones.
       - (Formula: Precision at rank k / total retrieved chunks).
    4. Answer Relevancy:
       - Measures if the generated answer directly addresses the question (doesn't include fluff or off-topic content).
       - Evaluated by generating questions back from the answer and measuring semantic similarity to the original query.
    """

    def __init__(self, provider: Optional[str] = None) -> None:
        """Initialize the evaluator and bind the configured LLM as the judge."""
        # Use Groq if explicitly requested, or if no provider specified and key is present
        use_groq = (provider == "groq") or (provider is None and bool(settings.groq_api_key))
        
        if use_groq:
            eval_llm = ChatOpenAI(
                model=settings.groq_model,
                openai_api_key=settings.groq_api_key,
                openai_api_base="https://api.groq.com/openai/v1",
                temperature=0.0
            )
        else:
            if not settings.gemini_api_key:
                raise ValueError("GEMINI_API_KEY is required for Ragas evaluation.")
            eval_llm = ChatGoogleGenerativeAI(
                model=settings.gemini_model,
                google_api_key=settings.gemini_api_key,
                temperature=0.0
            )

        if not settings.gemini_api_key:
            raise ValueError("GEMINI_API_KEY is required for Ragas evaluation embeddings.")
        eval_embeddings = GoogleGenerativeAIEmbeddings(
            model=f"models/{settings.embedding_model}" if not settings.embedding_model.startswith("models/") else settings.embedding_model,
            google_api_key=settings.gemini_api_key
        )
        
        # Wrap LangChain components for Ragas compatibility
        # We set bypass_n=True for Groq compatibility to avoid 'n must be at most 1' API errors
        self.ragas_llm = LangchainLLMWrapper(eval_llm, bypass_n=True if use_groq else False)
        self.ragas_embeddings = LangchainEmbeddingsWrapper(eval_embeddings)
        
        # Bind the LLM and Embeddings to the metrics
        self.metrics = [faithfulness, answer_relevancy, context_precision, context_recall]
        for metric in self.metrics:
            metric.llm = self.ragas_llm
            if hasattr(metric, "embeddings"):
                metric.embeddings = self.ragas_embeddings

    def evaluate_pipeline(
        self, 
        questions: List[str], 
        contexts: List[List[str]], 
        answers: List[str], 
        ground_truths: List[str]
    ) -> Dict[str, Any]:
        """
        Run the evaluation on a dataset of question-retrievals-answers.

        Args:
            questions: List of queries.
            contexts: List of lists containing the retrieved text chunks for each query.
            answers: List of answers generated by the system.
            ground_truths: List of ground truths.

        Returns:
            A dictionary containing the overall scores and detailed dataset row scores.
        """
        # Build dictionary formatted for HuggingFace Dataset
        data = {
            "question": questions,
            "contexts": contexts,
            "answer": answers,
            "ground_truth": ground_truths
        }
        
        dataset = Dataset.from_dict(data)
        
        from ragas.run_config import RunConfig
        
        # Limit concurrency for Groq to avoid hitting strict rate/concurrency limits
        run_config = RunConfig(
            max_workers=2 if settings.groq_api_key else 16,
            timeout=120,
            max_retries=10
        )
        
        # Run Ragas evaluation
        # Note: we pass our pre-configured metrics containing the Gemini wrappers
        result = evaluate(
            dataset=dataset,
            metrics=self.metrics,
            llm=self.ragas_llm,
            embeddings=self.ragas_embeddings,
            run_config=run_config
        )
        
        return result
